#if UNITY_EDITOR
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;
using static VfxKit.VfxBuildKit;

namespace VfxEffects
{
    /// <summary>
    /// Data for the web Mix Lab (Docs/VFX/_ArtDirection/tools/mix_lab/): every component prefab rendered at 30 fps
    /// from 2 fixed cameras (game 3/4 + side), all at the world origin so the layers line up when the web composites them.
    /// Each frame is shot on black and on white -> difference matte gives straight RGBA (alpha layers exact,
    /// additive layers approximated as screen-like). Also writes a background plate (1 m grid + 2 m capsule) per camera
    /// and mix_data.js (frames, durations, camera projection for offsets).
    /// </summary>
    public static class MixCapture
    {
        const string Out = "Docs/VFX/_ArtDirection/tools/mix_lab";
        const int Cell = 256, Cols = 8, Fps = 30, MaxFrames = 72;

        struct Cam { public string key; public Vector3 pos, look; }
        static readonly Cam[] Cams =
        {
            new Cam { key = "q", look = new Vector3(0f, 0.7f, 0f), pos = new Vector3(0f, 0.7f, 0f) + new Vector3(0f, Mathf.Sin(40f * Mathf.Deg2Rad), -Mathf.Cos(40f * Mathf.Deg2Rad)) * 8f },
            new Cam { key = "s", look = new Vector3(0f, 1.0f, 0f), pos = new Vector3(0f, 1.0f, -9f) },
        };

        [MenuItem("VFX/Components/Mix Lab - Capture Data")]
        public static void Capture()
        {
            if (!ConfirmSceneSwitch()) return;
            Directory.CreateDirectory(Out + "/data");
            var prefabs = AssetDatabase.FindAssets("t:Prefab", new[] { "Assets/VFX/_Components" })
                .Select(AssetDatabase.GUIDToAssetPath).Where(p => Path.GetFileName(p).StartsWith("CMP_")).OrderBy(p => p).ToList();

            EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            var cam = new GameObject("Cam").AddComponent<Camera>();
            cam.clearFlags = CameraClearFlags.SolidColor; cam.fieldOfView = 40f;
            var rt = new RenderTexture(Cell, Cell, 24, RenderTextureFormat.ARGB32);
            cam.targetTexture = rt;
            var tex = new Texture2D(Cell, Cell, TextureFormat.RGB24, false);
            var sb = new StringBuilder();
            sb.Append("/* Generated by MixCapture (Unity). Do not edit. */\nwindow.MIX_DATA = {\"fps\":" + Fps + ",\"cell\":" + Cell + ",\"cols\":" + Cols + ",\"cams\":{");

            // camera projection (for offsets/scale in the web) + background plates
            var stage = BuildStage();
            for (int c = 0; c < Cams.Length; c++)
            {
                Place(cam, Cams[c]);
                Vector2 o = Screen(cam, Vector3.zero);
                Vector2 ax = Screen(cam, Vector3.right) - o, ay = Screen(cam, Vector3.up) - o, az = Screen(cam, Vector3.forward) - o;
                stage.SetActive(true);
                cam.backgroundColor = new Color(0.08f, 0.085f, 0.1f);
                File.WriteAllBytes(Out + "/data/plate_" + Cams[c].key + ".png", Shot(cam, rt, tex).EncodeToPNG());
                stage.SetActive(false);
                sb.Append((c > 0 ? "," : "") + "\"" + Cams[c].key + "\":{\"o\":" + V(o) + ",\"x\":" + V(ax) + ",\"y\":" + V(ay) + ",\"z\":" + V(az) + "}");
            }
            sb.Append("},\"comps\":[");

            for (int i = 0; i < prefabs.Count; i++)
            {
                var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(prefabs[i]);
                var inst = (GameObject)PrefabUtility.InstantiatePrefab(prefab);
                inst.transform.position = Vector3.zero;
                var systems = inst.GetComponentsInChildren<ParticleSystem>(true);
                float dur = Duration(systems);
                int n = Mathf.Min(MaxFrames, Mathf.CeilToInt(dur * Fps) + 1);
                string id = prefab.name.Substring(4);
                string group = prefabs[i].Split('/')[3];
                bool add = false, alpha = false;
                foreach (var ps in systems)
                {
                    var m = ps.GetComponent<ParticleSystemRenderer>().sharedMaterial;
                    if (m && m.shader.name.Contains("Additive")) add = true; else alpha = true;
                }
                // One sheet per sortingOrder used inside the component, so the web can stack every LAYER where Unity puts it
                // (e.g. Impact Ground: flat star -4 under the smoke, splash 5 in front). Art lead 2026-11-03: "còn sai".
                var renderers = systems.Select(s => s.GetComponent<ParticleSystemRenderer>()).ToArray();
                var orders = renderers.Select(r => r.sortingOrder).Distinct().OrderBy(o => o).ToArray();
                foreach (int order in orders)
                {
                foreach (var r in renderers) r.enabled = r.sortingOrder == order;
                foreach (var cm in Cams)
                {
                    Place(cam, cm);
                    var atlas = new Texture2D(Cell * Cols, Cell * Mathf.CeilToInt(n / (float)Cols), TextureFormat.RGBA32, false);
                    atlas.SetPixels32(new Color32[atlas.width * atlas.height]);
                    for (int f = 0; f < n; f++)
                    {
                        float t = Mathf.Max(0.001f, f / (float)Fps);
                        foreach (var ps in systems) ps.Simulate(t, false, true, false);
                        cam.backgroundColor = Color.black; var b = Shot(cam, rt, tex).GetPixels32();
                        cam.backgroundColor = Color.white; var w = Shot(cam, rt, tex).GetPixels32();
                        var px = new Color32[b.Length];
                        for (int k = 0; k < b.Length; k++)
                        {
                            float br = b[k].r / 255f, bg = b[k].g / 255f, bb = b[k].b / 255f;
                            float a = 1f - Mathf.Min(w[k].r - b[k].r, Mathf.Min(w[k].g - b[k].g, w[k].b - b[k].b)) / 255f;
                            a = Mathf.Clamp01(Mathf.Max(a, Mathf.Max(br, Mathf.Max(bg, bb))));   // additive pixels: alpha = brightest channel
                            px[k] = a < 0.004f ? new Color32(0, 0, 0, 0)
                                : new Color32((byte)Mathf.Clamp(br / a * 255f, 0, 255), (byte)Mathf.Clamp(bg / a * 255f, 0, 255), (byte)Mathf.Clamp(bb / a * 255f, 0, 255), (byte)(a * 255f));
                        }
                        int col = f % Cols, row = f / Cols;
                        atlas.SetPixels32(col * Cell, atlas.height - (row + 1) * Cell, Cell, Cell, px);   // row 0 at the top of the PNG
                    }
                    atlas.Apply();
                    File.WriteAllBytes(Out + "/data/" + id + "_" + cm.key + "_o" + order + ".png", atlas.EncodeToPNG());
                    Object.DestroyImmediate(atlas);
                }
                }
                Object.DestroyImmediate(inst);
                string ctx = id.Contains("_Air_") ? "air" : id.Contains("_Dir_") ? "dir" : "ground";
                sb.Append((i > 0 ? "," : "") + "{\"id\":\"" + id + "\",\"group\":\"" + group + "\",\"context\":\"" + ctx + "\",\"frames\":" + n +
                          ",\"dur\":" + dur.ToString("0.###", System.Globalization.CultureInfo.InvariantCulture) +
                          ",\"blend\":\"" + (add && alpha ? "mixed" : add ? "add" : "alpha") + "\",\"orders\":[" + string.Join(",", orders) + "],\"prefab\":\"" + prefabs[i] + "\"}");
                Debug.Log("[MixCapture] " + id + "  " + n + " frames");
            }
            sb.Append("]};\n");
            File.WriteAllText(Out + "/mix_data.js", sb.ToString());
            cam.targetTexture = null; rt.Release();
            Debug.Log("[MixCapture] done: " + prefabs.Count + " components");
        }

        public static float Duration(ParticleSystem[] systems)
        {
            float d = 0.1f;
            foreach (var ps in systems)
            {
                var m = ps.main;
                float burst = 0f;
                var em = ps.emission;
                var bursts = new ParticleSystem.Burst[em.burstCount];
                em.GetBursts(bursts);
                foreach (var b in bursts) burst = Mathf.Max(burst, b.time);
                d = Mathf.Max(d, m.startDelay.constantMax + burst + m.startLifetime.constantMax);
            }
            return d + 0.05f;
        }

        static GameObject BuildStage()
        {
            var stage = new GameObject("Stage");
            var grid = ComponentKit.Unlit(new Color(0.2f, 0.21f, 0.24f));
            for (int i = -4; i <= 4; i++)
            {
                var x = GameObject.CreatePrimitive(PrimitiveType.Cube); x.GetComponent<Renderer>().sharedMaterial = grid; x.transform.SetParent(stage.transform);
                x.transform.position = new Vector3(i, 0f, 0f); x.transform.localScale = new Vector3(0.015f, 0.002f, 8f);
                var z = GameObject.CreatePrimitive(PrimitiveType.Cube); z.GetComponent<Renderer>().sharedMaterial = grid; z.transform.SetParent(stage.transform);
                z.transform.position = new Vector3(0f, 0f, i); z.transform.localScale = new Vector3(8f, 0.002f, 0.015f);
            }
            var human = GameObject.CreatePrimitive(PrimitiveType.Capsule);
            human.GetComponent<Renderer>().sharedMaterial = ComponentKit.Unlit(new Color(0.3f, 0.31f, 0.35f));
            human.transform.SetParent(stage.transform);
            human.transform.position = new Vector3(-1.6f, 1f, 0.3f); human.transform.localScale = new Vector3(0.6f, 1f, 0.6f);
            return stage;
        }

        static void Place(Camera cam, Cam c) { cam.transform.position = c.pos; cam.transform.LookAt(c.look); }

        static Texture2D Shot(Camera cam, RenderTexture rt, Texture2D tex)
        {
            cam.Render();
            RenderTexture.active = rt;
            tex.ReadPixels(new Rect(0, 0, Cell, Cell), 0, 0); tex.Apply();
            RenderTexture.active = null;
            return tex;
        }

        static Vector2 Screen(Camera cam, Vector3 w) { var p = cam.WorldToScreenPoint(w); return new Vector2(p.x, Cell - p.y); }
        static string V(Vector2 v) => "[" + v.x.ToString("0.##", System.Globalization.CultureInfo.InvariantCulture) + "," + v.y.ToString("0.##", System.Globalization.CultureInfo.InvariantCulture) + "]";

        public static void CaptureBatch() => RunBatch(Capture);
    }
}
#endif
